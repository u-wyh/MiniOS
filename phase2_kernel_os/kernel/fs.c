// 最小 ramfs 文件表：文件名 -> 内存数据 -> 大小
static struct file file_table[] = {
    {"init", (void*)init_elf, (uint32_t)sizeof(init_elf)},
    {"shell", (void*)shell_elf, (uint32_t)sizeof(shell_elf)},
    {"hello", (void*)hello_elf, (uint32_t)sizeof(hello_elf)},
    {"echo", (void*)echo_elf, (uint32_t)sizeof(echo_elf)},
    {"info", (void*)info_elf, (uint32_t)sizeof(info_elf)},
    {"loop", (void*)loop_elf, (uint32_t)sizeof(loop_elf)},
    {"fork", (void*)fork_elf, (uint32_t)sizeof(fork_elf)},
    {"execchild", (void*)execchild_elf, (uint32_t)sizeof(execchild_elf)},
    {"forkexec", (void*)forkexec_elf, (uint32_t)sizeof(forkexec_elf)}
};

// 统计文件数量，避免硬编码
static uint32_t fs_count(void) {
    return (uint32_t)(sizeof(file_table) / sizeof(file_table[0]));
}

// 最小字符串比较，仅用于文件名匹配
static int fs_str_equal(const char* a, const char* b) {
    uint32_t i = 0;

    while (a[i] != '\0' && b[i] != '\0') {
        if (a[i] != b[i]) {
            return 0;
        }
        i++;
    }

    return a[i] == '\0' && b[i] == '\0';
}

// 根据文件名查找文件，找到返回文件结构指针
struct file* fs_find(const char* name) {
    uint32_t i;

    if (name == (const char*)0 || name[0] == '\0') {
        return (struct file*)0;
    }

    for (i = 0; i < fs_count(); i++) {
        if (fs_str_equal(name, file_table[i].name) != 0) {
            return &file_table[i];
        }
    }

    return (struct file*)0;
}

// 列出当前所有文件，供 shell 的 ls 命令使用
void fs_list(void) {
    uint32_t i;

    for (i = 0; i < fs_count(); i++) {
        print_string(file_table[i].name);
        if (i + 1 < fs_count()) {
            print_char(' ');
        }
    }
    print_char('\n');
}

// 读取文件：当前最小实现直接复用 fs_find
struct file* fs_read(const char* name) {
    return fs_find(name);
}
