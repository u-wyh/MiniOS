// 最小程序表：程序名到内置 ELF 的映射
static struct program program_table[] = {
    {"hello", (void*)hello_elf},
    {"info", (void*)info_elf},
    {"loop", (void*)loop_elf}
};

// 计算程序表项个数，避免硬编码常量
static unsigned int exec_program_count(void) {
    return sizeof(program_table) / sizeof(program_table[0]);
}

// 最小字符串比较，仅用于程序名匹配
static int exec_str_equal(const char* a, const char* b) {
    int i = 0;

    while (a[i] != '\0' && b[i] != '\0') {
        if (a[i] != b[i]) {
            return 0;
        }
        i++;
    }

    return a[i] == '\0' && b[i] == '\0';
}

// 计算 ELF 镜像占用的最小字节长度，供 elf_load 传参
static unsigned int exec_get_elf_size(const unsigned char* elf_data) {
    const struct Elf32_Ehdr* ehdr = (const struct Elf32_Ehdr*)elf_data;
    const struct Elf32_Phdr* phdr;
    unsigned int end;
    unsigned int i;

    end = ehdr->e_phoff + ((unsigned int)ehdr->e_phnum * sizeof(struct Elf32_Phdr));
    phdr = (const struct Elf32_Phdr*)(elf_data + ehdr->e_phoff);

    for (i = 0; i < ehdr->e_phnum; i++) {
        unsigned int seg_end;

        if (phdr[i].p_type != PT_LOAD) {
            continue;
        }

        seg_end = phdr[i].p_offset + phdr[i].p_filesz;
        if (seg_end > end) {
            end = seg_end;
        }
    }

    return end;
}

// 在程序表中按名字查找 ELF，找到返回镜像地址，否则返回空指针
static const unsigned char* exec_find_program(const char* name) {
    unsigned int i;

    for (i = 0; i < exec_program_count(); i++) {
        if (exec_str_equal(name, program_table[i].name) != 0) {
            return (const unsigned char*)program_table[i].elf_data;
        }
    }

    return (const unsigned char*)0;
}

// 按程序名执行用户程序：shell 通过 run <name> 调用这里
void exec(const char* name) {
    const unsigned char* elf_image;
    unsigned int elf_size;
    unsigned int entry;

    if (name == (const char*)0 || name[0] == '\0') {
        print_string("exec: empty name\n");
        return;
    }

    elf_image = exec_find_program(name);
    if (elf_image == (const unsigned char*)0) {
        print_string("exec: program not found\n");
        return;
    }

    // 复用现有用户空间初始化，确保用户栈和基础映射已经准备好
    user_space_init();

    elf_size = exec_get_elf_size(elf_image);
    entry = elf_load(elf_image, elf_size);
    if (entry == 0) {
        print_string("exec: elf load failed\n");
        return;
    }

    // 最小 exec 流程：进入用户态执行 ELF 入口
    enter_user_mode(entry, USER_STACK_TOP);
}
